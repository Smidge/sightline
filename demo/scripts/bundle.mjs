// Bundles ../src into one script the demo injects into each page it reads.
// The function evaluates it over CDP, which page CSP doesn't block.
import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';

const result = await build({
  entryPoints: [new URL('../../src/index.ts', import.meta.url).pathname],
  bundle: true,
  format: 'iife',
  globalName: 'Sightline',
  target: 'es2022',
  minify: true,
  write: false,
});
const source = `${result.outputFiles[0].text};globalThis.__sightline = Sightline;`;
writeFileSync(
  new URL('../api/_sightline.ts', import.meta.url),
  `// Generated by scripts/bundle.mjs from ../src. Do not edit.\nexport const SIGHTLINE_SOURCE = ${JSON.stringify(source)};\n`,
);
console.log(`api/_sightline.ts: ${(source.length / 1024).toFixed(1)} KB`);
